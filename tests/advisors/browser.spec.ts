test('ADMIN registers staff, manually replaces organization advisor, keeps student independent, and withdraws',async({page})=>{
 const api=await advisorApi(page);await login(page);await page.goto('/app/admin/advisors')
 await expect(page.getByRole('heading',{name:'Asesores y responsabilidades'})).toBeVisible()
 await page.getByLabel('Cuenta de personal').selectOption(id(6));await page.getByLabel('Código de personal').fill('STAFF-6')
 await page.getByRole('button',{name:'Registrar personal',exact:true}).click()
 await expect.poll(()=>api.table('StaffProfiles').length).toBe(3)
 await page.getByRole('button',{name:'Asesores de organizaciones',exact:true}).click()
 await page.getByLabel('Nuevo asesor de organización').selectOption(id(103))
 await page.getByRole('button',{name:'Revisar responsabilidad de organización'}).click()
 const dialog=page.getByRole('dialog',{name:'Confirmar asesor de organización'});await expect(dialog).toBeVisible()
 expect(api.calls.some(row=>row.path.endsWith('/pyr_unibague_change_organization_advisor'))).toBe(false)
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible()
 await page.getByRole('button',{name:'Revisar responsabilidad de organización'}).click()
 await dialog.getByRole('button',{name:'Confirmar responsabilidad'}).click()
 await expect.poll(()=>api.table('AdvisorOrganizationAssignments').filter(row=>row.organization_id===id(201)).length).toBe(2)
 expect(api.table('AdvisorStudentAssignments').find(row=>row.participation_id===id(504))?.advisor_id).toBe(id(102))
 expect(api.calls.some(row=>row.path.endsWith('/pyr_unibague_change_student_advisor'))).toBe(false)
 await expect(page.getByText('Asesor vigente: Asesor B.')).toBeVisible()
 await page.getByLabel('Nuevo asesor de organización').selectOption('')
 await page.getByRole('button',{name:'Revisar responsabilidad de organización'}).click()
 await page.getByRole('dialog',{name:'Finalizar responsabilidad de organización'}).getByRole('button',{name:'Confirmar responsabilidad'}).click()
 await expect(page.getByText('Asesor vigente: Sin asignar.')).toBeVisible()
 expect(api.table('AdvisorOrganizationAssignments').filter(row=>row.organization_id===id(201)&&row.is_current)).toHaveLength(0)
})
