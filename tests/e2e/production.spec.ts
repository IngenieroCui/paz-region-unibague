import { expect, test } from '@playwright/test'
test('production excludes previews and keeps role routes closed', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /El conocimiento/ })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Vistas de desarrollo' })).toHaveCount(0)
  await page.goto('/dev/student')
  await expect(page.getByRole('heading', { name: 'No encontramos esta página' })).toBeVisible()
  await page.goto('/app/admin')
  await expect(page.getByRole('heading', { name: 'Bienvenido a tu espacio' })).toBeVisible()
})
test('PWA registers, serves a complete manifest and caches the public shell', async ({ page }) => {
  await page.goto('/')
  const manifestLink = page.locator('link[rel=manifest]')
  await expect(manifestLink).toHaveCount(1)
  const href = await manifestLink.getAttribute('href')
  expect(href).toBeTruthy()
  const response = await page.request.get(href!)
  const manifest = await response.json() as { name: string; icons: { src: string; purpose?: string }[] }
  expect(manifest.name).toBe('Paz y Región — Universidad de Ibagué')
  expect(manifest.icons.some(icon => icon.purpose === 'maskable')).toBe(true)
  for (const icon of manifest.icons) expect((await page.request.get(icon.src)).ok()).toBe(true)
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await page.context().setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: /El conocimiento/ })).toBeVisible()
  await page.context().setOffline(false)
})
